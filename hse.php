						    <h5>HSE AUDIT POLICY</h5>
						    <p>Due to the sophistication of all our equipment and work tools, nature of operations, unsafe acts and conditions are inevitable. These acts and conditions if not observed, checked and controlled or completely eliminated, can result in accidents.</p>
						    <p>Matong Energy Limited recognizes this fact and therefore has it as a policy to carry out frequent HSE Audit at all its work sites and operations.</p>
						    <p>All the nominated persons at each location are mandated to carry out site HSE audits as indicated by the schedule. Reports of such audits shall be forwarded to the project manager .The project HSE manager or the base manager as the case may be shall ensure corrective measures are implemented in good time. The project HSE management team ensures that training on HSE audit, management safety audits are carried out regularly. Reports are completed; recommendation made, followed up to ensure compliance and closed-out. It is the responsibility of all the work force to carryout HSE audit both in and outside their department’s area of operation and report to the site HSE office or their immediate supervisors. Repeated violation of audit recommendations will be discouraged and positive attitudes towards safety rewarded. This policy shall apply to all workforce and all are required to read, understand and abide by this policy.</p>
						    <h5>ALCOHOL AND DRUG POLICY</h5>
						    <p>Matong Energy Limited fundamental policy is set out to position her as one the leading companies in Nigeria through healthy competition and continuous innovation, with the aim of securing quality competitive advantage based on technology and strive for continuous improvement on total quality management by allowing employee participation.</p>
						    <p>Matong Energy Limited establishes and controls measurable Quality Objectives to achieve a Quality Policy, and establish the Quality Management System on a series of processes; planning, feasibility-study, engineering, purchasing, construction, supervising, delivering and servicing. In addition, the General Manager of Technical & Project Control Division, who is entitled to operate the quality management system, is nominated as management representative so that the system can work smoothly and steadily.All the management and employees should ensure the satisfaction and confidence of customers through complying with the quality management system, and improving the effectiveness of quality management system continuously.</p>
