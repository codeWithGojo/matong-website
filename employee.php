						    <h5>BUSINESS CONDUCT AND ETHICS</h5>
						    <p>Matong Energy Limited sets its fundamental policy to conduct its business in accordance with applicable laws, rules and regulations, with honesty and integrity, in a manner which demonstrate respect for local cultural and ethnic customs. Every manager bears responsibility for the employees entrusted to him / her.</p>
						    <p>Every manager must earn their respect by exemplary personal behavior performance, openness, and social competence. He / she shall set clear, ambitious, and realistic goals, lead by trust and confidence and leave the employees as much individual responsibility and leeway as possible. Every manager shall also be accessible in case employees wish to discuss a professional or personal problem. It will be the responsibility of every manager to see to it that there is no violation of laws within his/her area of responsibility which proper supervision could have prevented or rendered more difficult. The manager still remains responsible, if he/she delegates particular tasks. It is expected that every Matong Enegry Limited employee will transact business with the highest standard of integrity. Inappropriate behavior on the part of every single employee can cause the company considerable damage. Every employee should be concerned with the good reputation of Matong Enegry Limited in Nigeria. In all aspects of performing his/her job, every employee must focus on maintaining the good reputation of respect for the company.</p>
						    <h5>ALCOHOL AND DRUG POLICY</h5>
						    <p>It is the policy of Matong Energy Limited to have all her employees and subcontractors abide and comply with “No Alcohol and No Drug” policy during the time they are on duty. Every person must be in good mental and physical condition while executing an assigned task. Alcohol and hard drugs(Cocaine, Amphetamine, Marijuana, Heroin, and Hashish) or any product that has the ability to impair good judgment is prohibited. Any employee, subcontractor or third party found within Matong Enegry Limited premises or in control of Matong Enegry Limited vehicle under the influence of the afore-mentioned substance shall have services immediately terminated without compensation. This policy shall cover all Matong Enegry Limited’s operation areas.</p>
						    <h5>SMOKING POLICY</h5>
						    <p>Smoking is not only injurious but also a potential safety hazard. Smoking in public places exposes non-smokers to health related hazards and it is the duty of the Company to protect employees from unnecessary exposure to hazards. The smoking of cigarettes or pipes is prohibited in all non smoking designated areas. The ban also include conference / meeting rooms, corridors, public areas and shared offices, unless otherwise agreed between all occupants of such offices.</p>
						    <h5>SAFE INCENTIVES POLICY</h5>
						    <p>There will be an award known as “Safest Worker Award” to staff who exhibits best safe attitude at work monthly. It will be a cash prize to be determined by the Project Manager. The selection would be by a committee comprising the Project Manager, HSE Manager and the Site Manager.</p>
                            <p>The HSE committee shall use the following criteria for assessment:</p>
                             <li>Attendance to and involvement in mustering, toolbox briefings and safety meetings</li>
                             <li>Response to safety calls and warnings</li>
                             <li>Effective use and care for required and provided PPE(Personal Protective Equipment)</li>
                             <li>Neatness and good House – Keeping</li>
                             <li>Presentation of company I.D card and swimming pass on demand</li>
                             <li>Accident/Incident and hazards reporting</li>
                             <li>Safety suggestions.</li>
